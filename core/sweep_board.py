"""sweep leaderboard: the cumulative progress number (rules tested, passed, closest to pass). Pure functions.

reports/LEADERBOARD.json: {"legacy_hand_built_rules_failed", "runs": [one summary per config sha], "top10": [...]}.
A rerun of the same config file (same sha256) replaces its earlier entry, so reruns after an engine fix are not double counted.
"""
import time

LEGACY_HAND_BUILT = 60       # owner's count of hand-built rules that failed before the sweep engine ("over 60")


def empty():
    return {"legacy_hand_built_rules_failed": LEGACY_HAND_BUILT, "runs": [], "top10": [], "totals": {}}


def _key(r):
    return (-r["n_criteria"], r["val_p"], -(r["val_mean"] or -1.0))


def update(board, run):
    """run: {family, version, config_sha256, run_id, sha, utc, n_rules, n_gate_dropped, n_evaluated, n_errors, n_passed,
    holm_m, bonferroni_bar, top: [compact rows]}. Returns the new board."""
    b = board or empty()
    runs = [r for r in b.get("runs", []) if r.get("config_sha256") != run["config_sha256"]]
    runs.append(run)
    top = {}
    for r in runs:
        for x in r.get("top", []):
            k = (x.get("family"), x["id"])
            if k not in top or _key(x) < _key(top[k]):
                top[k] = x
    t10 = sorted(top.values(), key=_key)[:10]
    totals = {k: sum(r.get(k, 0) for r in runs) for k in ("n_rules", "n_gate_dropped", "n_evaluated", "n_errors", "n_passed")}
    totals["runs"] = len(runs)
    return {"legacy_hand_built_rules_failed": b.get("legacy_hand_built_rules_failed", LEGACY_HAND_BUILT), "runs": runs,
            "top10": t10, "totals": totals, "updated": run.get("utc") or time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}


def _pct(x):
    return "-" if x is None else f"{x * 100:+.3f}%"


def _num(x, f="{:.3g}"):
    return "-" if x is None else f.format(x)


def render_md(board):
    t = board.get("totals", {})
    L = ["# Sweep leaderboard", "",
         "Progress number of the TradeLab search (auto-generated by `research/sweeps/hooks.py` after every sweep run; do not edit by hand).", "",
         f"- **Rules tested (expanded): {t.get('n_rules', 0)}** across {t.get('runs', 0)} config file(s); evaluated after the step-0 gate: "
         f"{t.get('n_evaluated', 0)}; dropped by the gate: {t.get('n_gate_dropped', 0)}; errors: {t.get('n_errors', 0)}",
         f"- **Rules passed: {t.get('n_passed', 0)}**",
         f"- Before the engine: more than {board.get('legacy_hand_built_rules_failed', 0)} hand-built rules, all failed.", "",
         "Pass = validation and test net mean > 0 after costs and also at 2x costs, enough trades, validation p significant after Holm "
         "over the family, at least 70% of rolling 6-month folds positive, last 12 months positive at 2x cost.", "",
         "## Top 10 closest to pass", "",
         "| # | rule | criteria met (of 8; event rules 10) | val n | val mean/trade | val p | Holm p | test n | test mean/trade | val 2x | test 2x | 30d x median val/test | x |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(board.get("top10", []), 1):
        L.append(f"| {i} | `{r['family']}/{r['id']}` | {r['n_criteria']} | {r['val_n']} | {_pct(r['val_mean'])} | {_num(r['val_p'])} | "
                 f"{_num(r['p_adj'])} | {r['test_n']} | {_pct(r['test_mean'])} | {_pct(r['val_mean_2x'])} | {_pct(r['test_mean_2x'])} | "
                 f"{_num(r['val_mult30_median'])} / {_num(r['test_mult30_median'])} | {_num(r.get('x'))} |")
    nm = [(r["family"], x) for r in board.get("runs", []) for x in r.get("near_miss", [])]
    nm.sort(key=lambda z: -z[1]["x"])
    if nm:
        L += ["", "## Closest to the step-0 gate (dropped on train data; x = monthly contribution N*s^2, 2.2 needed for a median 3x month)", "",
              "| rule | x | train mean/trade | train trades | vol/cost | dropped because |", "|---|---|---|---|---|---|"]
        for fam, x in nm[:10]:
            L.append(f"| `{fam}/{x['id']}` | {_num(x['x'])} | {_pct(x['train_mean'])} | {x['n_train']} | {_num(x.get('vol_cost'))} | {x['reason']} |")
    L += ["", "## Runs", "", "| family | v | run | rules | gate-dropped | evaluated | errors | passed | Holm m | bar |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in board.get("runs", []):
        L.append(f"| {r['family']} | {r['version']} | {r.get('run_id') or '-'} | {r['n_rules']} | {r['n_gate_dropped']} | {r['n_evaluated']} | "
                 f"{r['n_errors']} | {r['n_passed']} | {r['holm_m']} | {_num(r.get('bonferroni_bar'))} |")
    return "\n".join(L) + "\n"
